"""Synthetic customer churn and retention data generator.

NOTE: All data generated by this module is synthetic and intended solely for
learning, pipeline demonstration, and portfolio analytics. It does NOT represent
actual customer data or real business records.
"""

from pathlib import Path
from datetime import date, timedelta
import random
import pandas as pd


def generate_data(output_dir, seed=77, customer_count=1000):
    """Generate reproducible synthetic customer, subscription, and payment event datasets.

    Parameters:
        output_dir (str or Path): Destination directory for generated CSV files.
        seed (int): Random seed for reproducibility (default: 77).
        customer_count (int): Number of customer records to generate (default: 1000).

    Returns:
        dict: Mapping of filenames to Path objects for the generated CSV files.
    """
    rng = random.Random(seed)
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    plans = [
        ("Basic", 9.99),
        ("Standard", 19.99),
        ("Premium", 34.99),
        ("Family", 44.99),
    ]
    contracts = [
        ("Month-to-Month", 0.55),
        ("One-Year", 0.30),
        ("Two-Year", 0.15),
    ]
    contract_names = [c[0] for c in contracts]
    contract_weights = [c[1] for c in contracts]

    payment_methods = [
        "Credit Card",
        "Bank Transfer",
        "UPI",
        "Electronic Check",
    ]
    cities = [
        "Pune",
        "Mumbai",
        "Delhi",
        "Bengaluru",
        "Hyderabad",
        "Chennai",
        "Lucknow",
    ]
    channels = ["organic", "paid_search", "referral", "social", "email"]

    customers = []
    subscriptions = []
    events = []

    start = date(2023, 1, 1)
    cutoff = date(2025, 12, 31)

    for cid in range(1, customer_count + 1):
        # Signup between 2023-01-01 and ~mid 2025
        signup_offset = rng.randint(0, 850)
        signup = start + timedelta(days=signup_offset)

        plan, price = rng.choice(plans)
        contract = rng.choices(contract_names, weights=contract_weights, k=1)[0]
        pay_method = rng.choice(payment_methods)

        # Realistic churn simulation:
        # Base churn rate depends strongly on contract type and payment method
        if contract == "Month-to-Month":
            base_churn_prob = 0.38
        elif contract == "One-Year":
            base_churn_prob = 0.14
        else:  # Two-Year
            base_churn_prob = 0.05

        # Electronic check or paid search slightly elevated churn
        if pay_method == "Electronic Check":
            base_churn_prob += 0.06
        elif pay_method in ("Credit Card", "UPI"):
            base_churn_prob -= 0.03

        # Plan price sensitivity
        if price >= 34.99:
            base_churn_prob += 0.03

        base_churn_prob = max(0.02, min(0.70, base_churn_prob))
        churned = rng.random() < base_churn_prob

        if churned:
            # Tenure between 15 and 650 days, capped at cutoff
            max_days = max(15, (cutoff - signup).days)
            tenure_days = rng.randint(15, min(650, max_days))
            churn_date = signup + timedelta(days=tenure_days)
            if churn_date > cutoff:
                churn_date = cutoff
            end_date = churn_date
            status = "churned"
        else:
            end_date = None
            status = "active"

        customers.append({
            "customer_id": cid,
            "customer_name": f"Customer {cid:05d}",
            "city": rng.choice(cities),
            "signup_date": signup,
            "acquisition_channel": rng.choice(channels),
        })

        subscriptions.append({
            "subscription_id": cid,
            "customer_id": cid,
            "plan_name": plan,
            "contract_type": contract,
            "payment_method": pay_method,
            "monthly_price": price,
            "start_date": signup,
            "end_date": end_date,
            "subscription_status": status,
        })

        # Payment event associated with subscription
        # Churned customers have a higher chance of a failed/refunded payment triggering churn
        if status == "churned":
            pay_status = rng.choices(
                ["paid", "failed", "refunded"], weights=[0.60, 0.28, 0.12], k=1
            )[0]
            event_dt = end_date
        else:
            pay_status = rng.choices(
                ["paid", "failed"], weights=[0.94, 0.06], k=1
            )[0]
            event_dt = cutoff

        events.append({
            "payment_event_id": cid,
            "subscription_id": cid,
            "event_date": event_dt,
            "payment_status": pay_status,
            "amount": price,
        })

    datasets = {
        "customers.csv": customers,
        "subscriptions.csv": subscriptions,
        "payment_events.csv": events,
    }

    paths = {}
    for name, rows in datasets.items():
        path = out / name
        pd.DataFrame(rows).to_csv(path, index=False)
        paths[name] = path

    return paths
